'use strict'
const { test, before, beforeEach } = require('node:test')
const assert = require('node:assert/strict')
const S = require('./node-setup.js')

before(async () => { await S.setup() })
beforeEach(() => { S.resetDb(); S.asUser('admin') })   // fresh DB for every test

const row = (name) => S.db.prepare('SELECT * FROM item WHERE name = ?').get(name)

test('framework loaded', () => {
  assert.equal(typeof CW.run, 'function')
  assert.equal(typeof CW.slugify, 'function')
  for (const d of ['Role', 'Task', 'User', 'Http', 'HtmlForm']) assert.ok(CW.Schema[d], 'schema ' + d)
  assert.ok(CW_FRAMEWORK_FILES.length >= 6)
})

test('no browser globals leaked', () => {
  assert.equal(typeof window, 'undefined')
  assert.equal(typeof document, 'undefined')
})

const SLUGS = [
  ['искусство переговоров', 'iskusstvo-peregovorov'],
  ['Управление конфликтами', 'upravlenie-konfliktami'],
  ['Эмоциональный интеллект', 'emocionalnyy-intellekt'],
  ['Выгорание: как не сгореть?', 'vygoranie-colon-kak-ne-sgoret-q'],
  ['Қазақстан әдемі', 'k-azak-stan-demi'],
  ['denis@nesen.org', 'denis-at-nesen-dot-org'],
  ['Manages conflict', 'manages-conflict'],
  ['Guest Visit', 'guest-visit'],
]
for (const [i, o] of SLUGS) test(`slugify "${i}"`, () => assert.equal(CW.slugify(i), o))

test('User update: _allowed_read persists (admin)', async () => {
  const r = await CW.run({
    operation: 'update', target_doctype: 'User',
    query: { where: { name: 'user01cc1bg14l1' } },
    target: { data: [{ name: 'user01cc1bg14l1' }] },
    input: { _allowed_read: ['roletracetest'] },
    options: { render: false },
  })
  assert.equal(r.success, true, 'error: ' + JSON.stringify(r.error))
  assert.deepEqual(JSON.parse(row('user01cc1bg14l1')._allowed_read), ['roletracetest'])
})

test('HtmlForm create round-trip', async () => {
  const r = await CW.run({
    operation: 'create', target_doctype: 'HtmlForm',
    input: { form_type: 'Guest Visit', title: 'Guest Visit', domain: S.DOMAIN },
    options: { render: false },
  })
  assert.equal(r.success, true, 'error: ' + JSON.stringify(r.error))
  const d = r.target?.data?.[0]
  assert.ok(d, 'no target data')
  assert.equal(d.slug, 'guest-visit')                 // slug is generated by generateSlug -> CW.slugify
  const r0 = S.db.prepare('SELECT * FROM item WHERE id = ?').get(d.id)
  assert.equal(r0.doctype, 'HtmlForm')
  assert.equal(JSON.parse(r0.data).slug, 'guest-visit')
})
